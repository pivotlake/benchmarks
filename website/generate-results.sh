#!/usr/bin/env bash
# Writes data.js, what index.html loads: every results/<benchmark>/<system>/*.json
# as `data`, one entry per line, and the query texts from ../benchmarks (TPC-H's
# and SSB's queries/*.sql, ClickBench's queries.sql from the submodule or the
# copy in queries/) as `queries`, so the page can show each query's SQL. Run it
# after adding a result and commit data.js with it; the page itself never
# changes.
set -euo pipefail
cd "$(dirname "$0")"

python3 - <<'PY'
import json, pathlib

entries = []
for path in sorted(pathlib.Path("results").glob("*/*/*.json")):
    entry = json.loads(path.read_text())
    entry.setdefault("benchmark", path.parts[1])
    entries.append(json.dumps(entry, separators=(",", ":")))

benchmarks = pathlib.Path("../benchmarks")
queries = {}
for bench in ("tpch", "ssb"):
    files = sorted((benchmarks / bench / "queries").glob("q*.sql"))
    if files:
        queries[bench] = [f.read_text().strip() for f in files]
# ClickBench's queries come from the submodule when it is checked out, else from the copy kept here.
for clickbench in (benchmarks / "clickbench" / "ClickBench" / "queries.sql", pathlib.Path("queries/clickbench.sql")):
    if clickbench.exists():
        queries["clickbench"] = [line for line in clickbench.read_text().splitlines() if line.strip()]
        break
query_lines = [f"{json.dumps(bench)}: {json.dumps(sql, ensure_ascii=False)}," for bench, sql in queries.items()]

lines = ["// Generated by generate-results.sh from results/ and the benchmarks' queries; do not edit.",
         "const data = [", ",\n".join(entries), "];", "", "const queries = {", *query_lines, "};", ""]
pathlib.Path("data.js").write_text("\n".join(lines))
print(f"{len(entries)} results, queries for {', '.join(queries) or 'no benchmark'}")
PY
