#!/usr/bin/env bash
# Bakes what index.html loads: data.js, every result under <results dir>
# (<benchmark>/<system>/<machine>[.sf<N>].json) as `data`, one entry per line;
# and queries.js, the query texts as `queries`, from ../benchmarks (TPC-H's and
# SSB's queries/*.sql, ClickBench's queries.sql from the submodule or the copy
# in queries/), when ../benchmarks is there: on the site box it is not, and
# queries.js comes with the page.
#
# Usage: ./generate-results.sh [results dir] [output dir]   (defaults: results, .)
set -euo pipefail
cd "$(dirname "$0")"
results="${1:-results}" out="${2:-.}"

python3 - "$results" "$out" <<'PY'
import json, pathlib, sys

results, out = (pathlib.Path(a) for a in sys.argv[1:3])
entries = []
for path in sorted(results.glob("*/*/*.json")):
    entry = json.loads(path.read_text())
    entry.setdefault("benchmark", path.parts[-3])
    entries.append(json.dumps(entry, separators=(",", ":")))
(out / "data.js").write_text("\n".join([
    "// Generated by generate-results.sh from the results; do not edit.",
    "const data = [", ",\n".join(entries), "];", ""]))
print(f"data.js: {len(entries)} results")

benchmarks = pathlib.Path("../benchmarks")
if not benchmarks.is_dir():
    print("queries.js: not written, ../benchmarks is not here")
    sys.exit()
queries = {}
for bench in ("tpch", "ssb"):
    files = sorted((benchmarks / bench / "queries").glob("q*.sql"))
    if files:
        queries[bench] = [f.read_text().strip() for f in files]
for clickbench in (benchmarks / "clickbench" / "ClickBench" / "queries.sql", pathlib.Path("queries/clickbench.sql")):
    if clickbench.exists():
        queries["clickbench"] = [line for line in clickbench.read_text().splitlines() if line.strip()]
        break
(out / "queries.js").write_text("\n".join([
    "// Generated by generate-results.sh from the benchmarks' queries; do not edit.",
    "const queries = {",
    *(f"{json.dumps(bench)}: {json.dumps(sql, ensure_ascii=False)}," for bench, sql in queries.items()),
    "};", ""]))
print(f"queries.js: {', '.join(queries) or 'no benchmark'}")
PY
